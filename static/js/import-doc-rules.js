async function saveDocumentRules(e) {
  e.preventDefault();
  const btn = document.getElementById('btnSaveRules');
  if (btn) { btn.disabled = true; btn.textContent = 'Salvando...'; }

  const updatedRules = currentDocRules.map((r, idx) => ({
    doc_type: r.doc_type,
    label: r.label,
    order_num: r.order_num || (idx + 1),
    required_on_water: document.getElementById(`req_water_${idx}`).checked,
    required_cleared: document.getElementById(`req_clear_${idx}`).checked,
    allow_post_attach: document.getElementById(`allow_post_${idx}`).checked
  }));

  try {
    const res = await fetch('/api/imports/document-rules', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ rules: updatedRules })
    });
    const data = await res.json();
    if (data.success) {
      handleRulesResponse(data);
      alert('✓ Regras documentais atualizadas com sucesso!');
      closeModal('docRulesModal');
    } else {
      alert('Erro ao salvar: ' + (data.message || 'Falha na requisição.'));
    }
  } catch (err) {
    alert('Erro ao salvar regras: ' + err.message);
  } finally {
    if (btn) { btn.disabled = false; btn.textContent = '💾 Salvar Alterações'; }
  }
}

async function resetDocumentRules() {
  if (!confirm('Deseja realmente restaurar as regras de documentos para o Padrão Oficial da MAJ?')) return;
  try {
    const res = await fetch('/api/imports/document-rules/reset', { method: 'POST' });
    const data = await res.json();
    if (data.success && data.rules) {
      handleRulesResponse(data);
      alert('✓ Regras restauradas para o padrão oficial com sucesso!');
    }
  } catch (err) {
    alert('Erro ao restaurar regras: ' + err.message);
  }
}

document.addEventListener('DOMContentLoaded', () => {
  loadDocumentRules();
});
