function handleRulesResponse(data) {
  if (data.rules) {
    currentDocRules = data.rules;
    if (data.core_types) coreDocTypes = data.core_types;
    renderDocRulesTable(currentDocRules);
    renderDocCategoriesList(currentDocRules);
  } else {
    loadDocumentRules();
  }
}

async function addNewDocumentCategory(e) {
  e.preventDefault();
  const label = (document.getElementById('newDocLabel')?.value || '').trim();
  const docType = (document.getElementById('newDocType')?.value || '').trim();
  if (!label || !docType) return alert('Por favor, preencha o nome e o código da categoria.');

  const btn = document.getElementById('btnAddNewDoc');
  if (btn) { btn.disabled = true; btn.textContent = 'Adicionando...'; }

  try {
    const res = await fetch('/api/imports/document-rules/add-category', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        doc_type: docType,
        label: label,
        required_on_water: document.getElementById('newDocReqWater').checked,
        required_cleared: document.getElementById('newDocReqCleared').checked,
        allow_post_attach: document.getElementById('newDocAllowPost').checked
      })
    });
    const data = await res.json();
    if (data.success) {
      alert('✓ Categoria "' + label + '" adicionada com sucesso!');
      document.getElementById('newDocLabel').value = '';
      document.getElementById('newDocType').value = '';
      handleRulesResponse(data);
    } else {
      alert('Erro: ' + (data.message || 'Falha na requisição.'));
    }
  } catch (err) {
    alert('Erro ao adicionar categoria: ' + err.message);
  } finally {
    if (btn) { btn.disabled = false; btn.textContent = '+ Adicionar Categoria'; }
  }
}

function openEditDocModal(docType) {
  const rule = currentDocRules.find(r => r.doc_type === docType);
  if (!rule) return;
  const isCore = coreDocTypes.includes(docType);

  document.getElementById('editDocTypeHidden').value = rule.doc_type;
  document.getElementById('editDocLabel').value = rule.label;
  document.getElementById('editDocTypeDisplay').textContent = rule.doc_type;
  document.getElementById('editDocReqWater').checked = !!rule.required_on_water;
  document.getElementById('editDocReqCleared').checked = !!rule.required_cleared;
  document.getElementById('editDocAllowPost').checked = !!rule.allow_post_attach;

  document.getElementById('editDocCoreWarning').style.display = isCore ? 'block' : 'none';
  const passInput = document.getElementById('editDocAdminPassword');
  passInput.value = '';
  passInput.required = isCore;

  document.getElementById('modalEditDocRule').style.display = 'flex';
}

async function saveEditDocRule(e) {
  e.preventDefault();
  const docType = document.getElementById('editDocTypeHidden').value;
  const label = document.getElementById('editDocLabel').value.trim();
  if (!label) return alert('O nome do documento não pode ficar vazio.');

  const btn = document.getElementById('btnSubmitEditDoc');
  if (btn) { btn.disabled = true; btn.textContent = 'Salvando...'; }

  try {
    const res = await fetch('/api/imports/document-rules/edit-category', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        doc_type: docType,
        label: label,
        required_on_water: document.getElementById('editDocReqWater').checked,
        required_cleared: document.getElementById('editDocReqCleared').checked,
        allow_post_attach: document.getElementById('editDocAllowPost').checked,
        admin_password: document.getElementById('editDocAdminPassword').value
      })
    });
    const data = await res.json();
    if (data.success) {
      alert('✓ Categoria atualizada com sucesso!');
      document.getElementById('modalEditDocRule').style.display = 'none';
      handleRulesResponse(data);
    } else {
      alert('Erro: ' + (data.message || 'Falha ao atualizar.'));
    }
  } catch (err) {
    alert('Erro ao salvar alteração: ' + err.message);
  } finally {
    if (btn) { btn.disabled = false; btn.textContent = 'Salvar Alterações'; }
  }
}

function openDuplicateDocModal(docType) {
  const rule = currentDocRules.find(r => r.doc_type === docType);
  if (!rule) return;
  const isCore = coreDocTypes.includes(docType);

  document.getElementById('dupDocSourceHidden').value = rule.doc_type;
  document.getElementById('dupDocSourceDisplay').textContent = `${rule.label} (${rule.doc_type})`;
  document.getElementById('dupDocNewLabel').value = `${rule.label} (Cópia)`;
  document.getElementById('dupDocNewType').value = `${rule.doc_type}_COPIA`;

  document.getElementById('dupDocCoreWarning').style.display = isCore ? 'block' : 'none';
  const passInput = document.getElementById('dupDocAdminPassword');
  passInput.value = '';
  passInput.required = isCore;

  document.getElementById('modalDuplicateDocRule').style.display = 'flex';
}

async function saveDuplicateDocRule(e) {
  e.preventDefault();
  const sourceDocType = document.getElementById('dupDocSourceHidden').value;
  const newLabel = document.getElementById('dupDocNewLabel').value.trim();
  const newDocType = document.getElementById('dupDocNewType').value.trim().toUpperCase();
  if (!newLabel || !newDocType) return alert('Informe o nome e o código da nova categoria.');

  const btn = document.getElementById('btnSubmitDupDoc');
  if (btn) { btn.disabled = true; btn.textContent = 'Duplicando...'; }

  try {
    const res = await fetch('/api/imports/document-rules/duplicate-category', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        source_doc_type: sourceDocType,
        new_doc_type: newDocType,
        new_label: newLabel,
        admin_password: document.getElementById('dupDocAdminPassword').value
      })
    });
    const data = await res.json();
    if (data.success) {
      alert('✓ Categoria "' + newLabel + '" duplicada com sucesso!');
      document.getElementById('modalDuplicateDocRule').style.display = 'none';
      handleRulesResponse(data);
    } else {
      alert('Erro: ' + (data.message || 'Falha ao duplicar.'));
    }
  } catch (err) {
    alert('Erro ao duplicar: ' + err.message);
  } finally {
    if (btn) { btn.disabled = false; btn.textContent = 'Confirmar Duplicação'; }
  }
}

